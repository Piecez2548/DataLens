export function t(text: string): string {
  return current === "th" ? (th[text] ?? text) : text;
}

const reasonRules: [RegExp, (m: RegExpMatchArray) => string][] = [
  [/^Blank or marked as missing$/, () => "ว่างหรือถูกกำหนดให้เป็นค่าว่าง"],
  [/^Repeats an earlier row$/, () => "ซ้ำกับแถวก่อนหน้า"],
  [/^Does not look like (.+)$/, (m) => `ไม่เหมือนชนิด ${m[1]}`],
  [/^Not a finite number$/, () => "ไม่ใช่ตัวเลขที่ใช้ได้"],
  [/^Not a valid calendar date$/, () => "ไม่ใช่วันที่ที่มีอยู่จริง"],
  [/^Not a valid email shape$/, () => "รูปแบบอีเมลไม่ถูกต้อง"],
  [/^Thai national ID check digit is wrong$/, () => "เลขตรวจสอบของเลขบัตรประชาชนไม่ถูกต้อง"],
  [/^Outside the 1\.5×IQR range (.+) to (.+)$/, (m) => `อยู่นอกช่วง 1.5×IQR (${m[1]} ถึง ${m[2]})`],
  [/^Required value is blank$/, () => "ค่าที่ต้องมีเป็นค่าว่าง"],
  [/^Value is not in the allowed list$/, () => "ค่าไม่อยู่ในรายการที่อนุญาต"],
  [/^Below the minimum (.+)$/, (m) => `ต่ำกว่าค่าต่ำสุด ${m[1]}`],
  [/^Above the maximum (.+)$/, (m) => `สูงกว่าค่าสูงสุด ${m[1]}`],
  [/^Repeats a key first seen at row (\d+)$/, (m) => `คีย์ซ้ำกับที่พบครั้งแรกที่แถว ${m[1]}`],
];

export function tReason(reason: string): string {
  if (current !== "th") return reason;
  for (const [pattern, build] of reasonRules) {
    const match = reason.match(pattern);
    if (match) return build(match);
  }
  return reason;
}
